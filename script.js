const $=id=>document.getElementById(id);
let history=JSON.parse(localStorage.getItem("nexora_history")||"[]");

function showPanel(name,btn){
  document.querySelectorAll(".panel").forEach(p=>p.classList.remove("active"));
  $(""+name+"Panel").classList.add("active");
  document.querySelectorAll(".side").forEach(b=>b.classList.remove("active"));
  if(btn) btn.classList.add("active");
}
function openLab(name){showPanel(name,document.querySelectorAll(".side")[name==="code"?1:0]);document.querySelector(".workspace").scrollIntoView({behavior:"smooth"})}
function focusChat(){showPanel("chat",document.querySelector(".side"));$("chatInput").focus();document.querySelector(".workspace").scrollIntoView({behavior:"smooth"})}
function addMessage(role,text){
  const d=document.createElement("div"); d.className="msg "+role;
  d.innerHTML=`<div class="avatar">${role==="ai"?"N":"Y"}</div><div><b>${role==="ai"?"NEXORA":"YOU"}</b><p></p></div>`;
  d.querySelector("p").textContent=text;$("messages").appendChild(d);$("messages").scrollTop=$("messages").scrollHeight;
}
async function sendMessage(){
  const input=$("chatInput"), text=input.value.trim(); if(!text)return;
  addMessage("user",text); input.value="";
  history.push({role:"user",text}); localStorage.setItem("nexora_history",JSON.stringify(history.slice(-50)));
  const loading="NEXORA is processing...";
  addMessage("ai",loading);
  const last=$("messages").lastElementChild.querySelector("p");
  try{
    const r=await fetch("/api/chat",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({message:text,history:history.slice(0,-1),model:$("model").value})});
    const data=await r.json(); if(!r.ok)throw Error(data.detail||"Request failed");
    last.textContent=data.reply||"No response received.";
    history.push({role:"assistant",text:data.reply||""});localStorage.setItem("nexora_history",JSON.stringify(history.slice(-50)));
  }catch(e){last.textContent="Connection error: "+e.message}
}
$("chatInput").addEventListener("keydown",e=>{if(e.key==="Enter"&&!e.shiftKey){e.preventDefault();sendMessage()}});
async function searchWeb(){
  const q=$("searchInput").value.trim();if(!q)return;
  $("searchResults").innerHTML="<p>Searching...</p>";
  try{const r=await fetch("/api/search?q="+encodeURIComponent(q));const d=await r.json();if(!r.ok)throw Error(d.detail||"Search failed");
    $("searchResults").innerHTML=(d.results||[]).map(x=>`<div class="result"><a href="${x.url}" target="_blank" rel="noopener">${escapeHtml(x.title||x.url)}</a><p>${escapeHtml(x.snippet||"")}</p></div>`).join("")||"<p>No results found.</p>";
  }catch(e){$("searchResults").innerHTML="<p>"+escapeHtml(e.message)+"</p>"}
}
function generateImage(){
  const p=$("imagePrompt").value.trim();if(!p)return;
  const url="/api/image?prompt="+encodeURIComponent(p);
  $("imageResult").innerHTML=`<p>Generating image...</p><img src="${url}" alt="Generated by NEXORA" onload="this.previousElementSibling.remove()" onerror="this.previousElementSibling.textContent='Image provider unavailable.'">`;
}
async function generateVideo(){
  const p=$("videoPrompt").value.trim();if(!p)return;
  $("videoResult").innerHTML="<p>Submitting video job...</p>";
  try{const r=await fetch("/api/video",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({prompt:p})});const d=await r.json();$("videoResult").innerHTML="<p>"+escapeHtml(d.message||d.detail||"Job submitted.")+"</p>"}catch(e){$("videoResult").innerHTML="<p>Video service is not configured yet.</p>"}
}
