function quick(t){showPanel("chat",document.querySelector(".side"));$("chatInput").value=t;sendMessage()}
function escapeHtml(s){return String(s).replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#039;"}[c]))}
